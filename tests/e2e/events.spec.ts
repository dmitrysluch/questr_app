import { test, expect, type Page } from '@playwright/test';
async function character(page: Page, name: string) {
  await expect.poll(async () => (await page.request.get('/api/health')).status()).toBe(200);
  await page.request.post('/api/auth/demo', { data: {} });
  const state = await (await page.request.get('/api/me')).json();
  const { draft } = await (await page.request.post('/api/register', { data: { displayName: name, invite: state.demoInvite, adult: true, terms: true, locale: 'en' } })).json();
  const saved = await (await page.request.put('/api/draft', { data: { ...draft, avatarId: 'moss', spokenLanguages: ['en'], introMarkdown: `I am ${name}. Coffee and records are my thing.` } })).json();
  expect((await page.request.post('/api/profile/publish', { data: { revision: saved.draft.revision } })).status()).toBe(200);
  await page.request.put('/api/discovery', { data: { revision: 0, locationIds: ['country:IL'], languageCodes: ['en'] } });
  return state.user.id as string;
}
async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); }
test('create an adventure, apply from another character, accept, edit and withdraw', async ({ page, browser }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await character(page, 'Record keeper');
  await page.goto('/#adventures');
  await page.getByRole('button', { name: 'Create adventure', exact: true }).click();
  const editor = page.getByRole('dialog');
  await editor.getByLabel('Adventure title', { exact: true }).fill('Coffee, records & a slow afternoon');
  await editor.getByLabel('What are we doing?', { exact: true }).fill('Bring **one record** you love. We will listen over coffee.');
  await editor.getByLabel('Date & time', { exact: true }).fill('2030-06-15T19:30');
  await editor.getByLabel('Time zone', { exact: true }).selectOption('Asia/Jerusalem');
  await editor.getByRole('combobox', { name: 'Where', exact: true }).fill('Haifa');
  await editor.getByRole('option', { name: 'Haifa Israel', exact: true }).click();
  await editor.getByLabel('Party size', { exact: true }).fill('3');
  await editor.getByLabel('Meeting details', { exact: true }).fill('Private door 42, ring the bell');
  await page.screenshot({ path: `.artifacts/${info.project.name}-adventure-editor.png`, fullPage: true });
  await editor.getByRole('button', { name: 'Publish adventure' }).click();
  await expect(page.getByRole('heading', { name: 'Coffee, records & a slow afternoon', level: 1 })).toBeVisible();
  await expect(page.locator('.meeting-details')).toContainText('Private door 42');
  const hash = await page.evaluate(() => location.hash);
  await page.reload();
  await expect(page.locator('.meeting-details')).toContainText('Private door 42');
  const guestContext = await browser.newContext({ viewport: page.viewportSize()!, baseURL: new URL(page.url()).origin });
  const guest = await guestContext.newPage();
  const base = new URL(page.url()).origin;
  await character(guest, 'Jazz questr');
  await guest.goto(`${base}/${hash}`);
  await expect(guest.getByRole('heading', { name: 'Coffee, records & a slow afternoon', level: 1 })).toBeVisible();
  await expect(guest.locator('.meeting-details')).toHaveCount(0);
  await guest.getByRole('button', { name: 'Apply', exact: true }).click();
  await guest.getByLabel('Message to the host').fill('I will bring my favourite Bill Evans record.');
  await guest.getByRole('button', { name: 'Send application' }).click();
  await expect(guest.getByRole('status')).toContainText('Waiting for the host');
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.locator('.application')).toContainText('Bill Evans');
  await page.locator('.application .person-button').click();
  await expect(page.getByRole('dialog').locator('.profile-body')).toContainText('Jazz questr');
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Accept', exact: true }).click();
  await guest.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(guest.locator('.meeting-details')).toContainText('Private door 42');
  await expect(guest.locator('.party-person')).toHaveCount(2);
  await noOverflow(page); await noOverflow(guest);
  await page.screenshot({ path: `.artifacts/${info.project.name}-adventure-host.png`, fullPage: true });
  await guest.screenshot({ path: `.artifacts/${info.project.name}-adventure-party.png`, fullPage: true });
  await page.getByRole('button', { name: 'Edit adventure' }).click();
  await page.getByRole('dialog').getByLabel('Meeting details', { exact: true }).fill('Updated private door 43');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await guest.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(guest.locator('.meeting-details')).toContainText('Updated private door 43');
  await guest.getByRole('button', { name: 'Leave party' }).click();
  await guest.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click();
  await expect(guest.getByRole('heading', { name: 'Adventures', exact: true })).toBeVisible();
  await guest.goto(`${base}/${hash}`);
  await expect(guest.locator('.membership-status')).toHaveText('Application withdrawn');
  await expect(guest.locator('.meeting-details')).toHaveCount(0);
  await page.getByRole('button', { name: 'Cancel adventure', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click();
  await expect(page.locator('.event-status')).toHaveText('Cancelled');
  await guestContext.close(); expect(errors).toEqual([]);
});
